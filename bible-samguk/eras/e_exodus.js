// 성경 삼국지 — 시대 2: 출애굽과 가나안 정복 (BC 1446, 출애굽기·민수기·여호수아)
// 플레이어는 언제나 "마하나임 하나님의 군대"(army). 모세 → 여호수아가 이끈다.
// 고센 → 홍해 → 르비딤(여호와 닛시) → 시내 산(언약·성막) → 가데스 바네아 → 요단 동편(시혼·옥) → 여리고 → 가나안.
// 옛 시나리오 conquest의 사건·대화를 옮겨 오고, 출애굽과 광야 사건을 더했다.

const EXO = {
  on: (G, cid) => !!G.city(cid),
  own: (G, cid) => EXO.on(G, cid) && G.ownerOf(cid) === 'army',
  owned: (G, cid, f) => EXO.on(G, cid) && G.exists(f) && G.ownerOf(cid) === f,
  sc: () => SCENARIOS.find(s => s.id === 'e_exodus'),
  raise: (G, name, cid, lead) => {
    if (!G.exists('army') || !G.alive(name)) return false;
    if (G.facOf(name) !== 'army') G.join(name, 'army', cid && EXO.own(G, cid) ? cid : undefined);
    if (lead) G.setRuler('army', name);
    return true;
  },
  // 앞 사건이 끝나고 정해진 턴이 지났는가
  after: (G, id) => !!G.done[id] && G.turn >= (G.flags.xNext || 0) && G.exists('army'),
  next: (G, n) => { G.flags.xNext = G.turn + n; },
  faithAll: (G, d, loy) => { if (G.exists('army')) G.eachCity('army', c => { c.faith += d; if (loy) c.loy += loy; }); },
  trainAll: (G, d) => { if (G.exists('army')) G.eachCity('army', c => { c.train = Math.min(100, c.train + d); }); },
  cut: (G, f, k, only) => { if (G.exists(f)) G.eachCity(f, c => { if (!only || only.includes(c.id)) c.soldiers = Math.floor(c.soldiers * k); }); },
  pay: (G, gold, food) => { if (!G.exists('army')) return; const F = G.fac('army'); F.gold = Math.max(0, F.gold - gold); F.food = Math.max(0, F.food - food); },
  gain: (G, gold, food) => { if (!G.exists('army')) return; const F = G.fac('army'); F.gold += gold || 0; F.food += food || 0; },
  stat: (G, name, k, d) => { const o = G.o(name); if (o && o.alive) o[k] = Math.max(0, Math.min(100, o[k] + d)); },
  home: G => {
    if (!G.exists('army')) return null;
    const cap = G.fac('army').capital;
    if (EXO.own(G, cap)) return G.city(cap);
    let best = null; G.eachCity('army', c => { if (!best || c.soldiers > best.soldiers) best = c; });
    return best;
  },
  add: (G, n) => { const h = EXO.home(G); if (h) h.soldiers += n; return h; },
  settle: (G, cid, sold, loy) => {
    if (!G.exists('army') || !EXO.on(G, cid)) return false;
    const c = G.city(cid); if (c.owner) return false;
    c.owner = 'army'; c.soldiers += sold; c.loy = loy; c.faith += 10; return true;
  },
  // 다른 세력의 장수를 그 도읍으로 돌려보낸다 (성의 주인이 바뀔 때)
  evict: (G, cid) => {
    EXO.sc().officers.forEach(r => { const o = G.o(r[0]); if (o && o.alive && o.city === cid && o.fac !== 'army') { if (o.fac && G.exists(o.fac) && G.fac(o.fac).capital !== cid) o.city = G.fac(o.fac).capital; else if (!o.fac) o.city = cid; } });
  },
  // 출애굽: 고센의 백성이 홍해를 건너 시내 광야로 (출 12:37; 14–15장)
  exodus: G => {
    if (!G.exists('army')) return '';
    const g = EXO.on(G, 'goshen') ? G.city('goshen') : null, s = EXO.on(G, 'sinai') ? G.city('sinai') : null;
    if (!g || !s || g.owner !== 'army' || s.owner === 'army') return '';
    if (s.owner && G.fac(s.owner).capital === 'sinai') return ''; // 시내 산이 누군가의 도읍이면 옮기지 않는다
    EXO.evict(G, 'sinai');
    s.owner = 'army'; s.soldiers = Math.max(s.soldiers, 0) + Math.floor(g.soldiers * 0.9); s.loy = 85; s.faith += 15; s.train = Math.max(s.train, g.train);
    EXO.sc().officers.forEach(r => { const o = G.o(r[0]); if (o && o.alive && o.fac === 'army' && o.city === 'goshen') o.city = 'sinai'; });
    G.fac('army').capital = 'sinai';
    if (G.exists('egypt')) { g.owner = 'egypt'; g.soldiers = 800; g.loy = 40; } else { g.owner = null; g.soldiers = 300; }
    return ' 온 백성이 고센을 떠나 시내 광야에 진을 쳤다 — 하나님의 군대의 본진이 시내 산이 되었다(고센은 다시 애굽 땅).';
  },
};

