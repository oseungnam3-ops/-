def art(name, scn=None):
    if scn:
        s = next((x for x in D['scn'] if x['id'] == scn), None)
        if s and name in s['artmap']:
            return s['artmap'][name]
        if ART.get(scn + ':' + name):
            return ART[scn + ':' + name]
    return ART.get(name) or next((v for k, v in ART.items() if k.endswith(':' + name)), '')


def shot(n, cap, w='62mm'):
    if n.startswith('img:'):
        img = f'<img src="img/{n[4:]}.jpg" alt="">'
    elif SPRITE:
        x = SHOTS.index(n) * 100 / (len(SHOTS) - 1)
        img = f'<div class="sp" style="background-image:url(\'{SPRITE}\');background-size:{len(SHOTS) * 100}% 100%;background-position:{x:.4f}% 0"></div>'
    else:
        img = f'<img src="shots/{n}.png" alt="">'
    return f'<figure class="shot" style="width:{w}">{img}<figcaption>{cap}</figcaption></figure>'


def tip(t, kind='tip'):
    icon = {'tip': '💡 도움말', 'warn': '⚠️ 주의', 'bible': '📖 말씀'}[kind]
    return f'<div class="box {kind}"><b>{icon}</b><div>{t}</div></div>'


def table(head, rows, cls=''):
    h = ''.join(f'<th>{x}</th>' for x in head)
    b = ''.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table class="{cls}"><thead><tr>{h}</tr></thead><tbody>{b}</tbody></table>'


def steps(items):
    return '<ol class="steps">' + ''.join(f'<li>{x}</li>' for x in items) + '</ol>'


